-- AI assistant sidebar, toggled from the Quickshell bar (AiAssistant.qml).
-- It parks on the special:ai workspace so one dispatch slides it in and out.
--
-- Chromium ignores --class in --app mode and derives its Wayland app id from the
-- URL (chrome-www.kimi.com__-Default), so this matches the prefix every Chromium
-- web app shares. That means changing QS_AI_URL is enough to swap assistants —
-- nothing here needs editing. The standalone launchers in ~/Nuketown/Webapps
-- open in kiosk mode (class "chromium") precisely so this doesn't catch them.
hl.window_rule({
    name  = "ai-assistant",
    match = { class = "chrome-.*" },

    float     = true,
    size      = "460 748",
    move      = "8 42",
    workspace = "special:ai silent",

    -- It is docked to the left edge, so it should arrive from the left. Hyprland
    -- picks the direction itself for special-workspace animations, which is why
    -- this is set per-window. If it still enters from the wrong side, the other
    -- lever is the specialWorkspaceIn/Out style above.
    animation = "slide left",
})

-- Quickshell wallpaper picker (WallpaperPicker.qml). Its scrim is only ~22%
-- opaque, so ignore_alpha has to sit below that or nothing gets blurred.
hl.layer_rule({
    name  = "wallpaper-picker",
    match = { namespace = "^quickshell:wallpaper-picker$" },

    blur         = true,
    ignore_alpha = 0.1,
})

-- The new wallpaper growing in from the middle (WallpaperReveal.qml). The
-- animation is drawn by Quickshell, so Hyprland's own layer fade would only
-- fight it.
hl.layer_rule({
    name  = "wallpaper-reveal",
    match = { namespace = "^quickshell:wallpaper-reveal$" },

    no_anim = true,
})

-- The bar (namespace "quickshell"): frosted glass behind its pills and behind
-- every panel that drops out of it (control center, Wi-Fi, clipboard…), as in
-- the design. ignore_alpha keeps the fully transparent gaps unblurred.
hl.layer_rule({
    name  = "bar-glass",
    match = { namespace = "^quickshell$" },

    blur         = true,
    blur_popups  = true,
    ignore_alpha = 0.3,
})

-- The control center (MorphPanel.qml) grows out of the status pill and animates
-- itself; it gets the same frosted glass as the bar, and no layer fade.
hl.layer_rule({
    name  = "panel-glass",
    match = { namespace = "^quickshell:panel$" },

    blur         = true,
    ignore_alpha = 0.3,
    no_anim      = true,
})

-- Workspace previews (WorkspacePreview.qml): frosted, and animate themselves.
